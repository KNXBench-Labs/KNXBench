/** Pins exact TypeDate source admission and lossless Gregorian date lexical preflight. */
import { describe, expect, it } from "vitest";
import { chooseParameterEditor, parameterDraftIssue, type ParameterEditorField, type ParameterEditorSource } from "./plan";

const field: ParameterEditorField = { etsId: "PR", kind: "Date", value: "1899-12-31", min: null, max: null, editable: true, writeEtsId: "WRITE-DATE", access: "ReadWrite" };
const source: ParameterEditorSource = { sourceSha256: "a".repeat(64), programId: "A", parameterRefId: "PR", parameterTypeId: "PT", schema: 21, child: "TypeDate", attributes: { Encoding: "DPT 11" }, parentAttributes: { Id: "PT" } };
const context = { programId: "A", sourceSha256: "a".repeat(64), moduleScoped: false };

// Independent expectations, not generated by the implementation or the browser's Date API.
const valid = [
  "0000-01-01", "0000-02-29", "0001-01-01", "0001-02-28", "1899-12-31",
  "1900-02-28", "1990-01-01", "2000-02-29", "2024-02-29", "2089-12-31",
  "2090-01-01", "9999-12-31", "2026-01-31", "2026-04-30", "2026-06-30",
  "2026-07-31", "2026-08-31", "2026-09-30", "2026-10-31", "2026-11-30",
];
const invalid = [
  "", "date", "0001-02-29", "1899-02-29", "1900-02-29", "2001-02-29", "2100-02-29",
  "2000-02-30", "2026-00-01", "2026-13-01", "2026-01-00", "2026-01-32",
  "2026-04-31", "2026-06-31", "2026-09-31", "2026-11-31", "9999-02-29",
  "10000-01-01", "999-01-01", "26-01-01", "2026-1-01", "2026-01-1", "2026/01/01",
  "+2026-01-01", "-001-01-01", " 2026-01-01", "2026-01-01 ", "2026-01-01\t",
  "2026-01-01\n", "2026-01-01\r", "2026-01-01\r\n", "2026-01-\n01", "2026-01-01\n2000-02-29",
  "2026-01-01Z", "2026-01-01+01:00", "2026-01-01T00:00:00", "2026-01-01\u0000",
  "２０２６-01-01", "٢٠٢٦-01-01", "2026-０１-01", "2026-01-٠١", "2026–01–01",
];

describe("checked Date literal contract", () => {
  it.each(valid)("accepts exact calendar date %j without a DPT11 year restriction", raw => {
    expect(parameterDraftIssue(chooseParameterEditor(field, source, context), raw)).toBeNull();
  });
  it.each(invalid)("refuses noncalendar or nonliteral date %j without rewriting it", raw => {
    expect(parameterDraftIssue(chooseParameterEditor(field, source, context), raw)).toBe("date");
  });
  it("admits the exact declaration in schemas 20..23 independently of historical values", () => {
    for (const schema of [20, 21, 22, 23]) for (const value of [null, "", "invalid", "1900-02-29", "2000-02-29\r\n"]) {
      expect(chooseParameterEditor({ ...field, value }, { ...source, schema }, context)).toEqual({ kind: "date-literal" });
    }
    expect(chooseParameterEditor(field, { ...source,
      attributes: { Encoding: "DPT 11", xmlns: "urn:example", "xmlns:v": "urn:vendor" },
      parentAttributes: { Id: "PT", Name: "Date", xmlns: "urn:example", "xmlns:v": "urn:vendor" },
    }, context)).toEqual({ kind: "date-literal" });
  });
  it("requires the exact raw Encoding token and refuses every additional child hint", () => {
    const attributes: Record<string, string>[] = [
      {}, { Encoding: "" }, { Encoding: "DPT11" }, { Encoding: "dpt 11" }, { Encoding: "DPT 11\n" },
      { Encoding: "DPT 10" }, { "v:Encoding": "DPT 11" },
      ...["UIHint", "Unit", "SizeInBit", "Increment", "Type", "Unknown", "v:UIHint", "v:Encoding", "{urn:vendor}Encoding"]
        .map(key => ({ Encoding: "DPT 11", [key]: "x" })),
    ];
    for (const a of attributes) {
      expect(chooseParameterEditor(field, { ...source, attributes: a }, context)).toEqual({ kind: "fallback", reason: "unsupported-hints" });
    }
  });
  it("admits only Id, optional Name and namespaces on the parent", () => {
    for (const key of ["Encoding", "UIHint", "Unit", "SizeInBit", "Increment", "Unknown", "v:Name", "v:Id", "{urn:vendor}Name"]) {
      expect(chooseParameterEditor(field, { ...source, parentAttributes: { Id: "PT", [key]: "x" } }, context))
        .toEqual({ kind: "fallback", reason: "unsupported-hints" });
    }
    const invalidParents: Record<string, string>[] = [{}, { Id: "other" }, { "v:Id": "PT" }];
    for (const parentAttributes of invalidParents) {
      expect(chooseParameterEditor(field, { ...source, parentAttributes }, context)).toEqual({ kind: "fallback", reason: "source-conflict" });
    }
  });
  it("retains common identity, schema, null-bound and module-scope refusals", () => {
    for (const changed of [
      { sourceSha256: "b".repeat(64) }, { sourceSha256: "a".repeat(63) + "\n" },
      { sourceSha256: "a".repeat(64) + "\n" }, { programId: "other" }, { parameterRefId: "other" },
      { parameterTypeId: "other" }, { child: "v:TypeDate" }, { child: "TypeTime" }, { schema: 19 }, { schema: 24 },
    ]) {
      expect(chooseParameterEditor(field, { ...source, ...changed }, context)).toEqual({ kind: "fallback", reason: "source-conflict" });
    }
    for (const bound of ["min", "max"] as const) {
      expect(chooseParameterEditor({ ...field, [bound]: "0" }, source, context)).toEqual({ kind: "fallback", reason: "source-conflict" });
      expect(chooseParameterEditor({ ...field, [bound]: "0" }, { ...source, attributes: { Encoding: "DPT 11", [`${bound}Inclusive`]: "0" } }, context))
        .toEqual({ kind: "fallback", reason: "unsupported-hints" });
    }
    expect(chooseParameterEditor(field, null, context)).toEqual({ kind: "fallback", reason: "missing-evidence" });
    expect(chooseParameterEditor(field, source, { ...context, moduleScoped: true })).toEqual({ kind: "fallback", reason: "module-scope" });
    expect(chooseParameterEditor(field, source, { ...context, programId: "other" })).toEqual({ kind: "fallback", reason: "source-conflict" });
    expect(chooseParameterEditor(field, source, { ...context, sourceSha256: "b".repeat(64) })).toEqual({ kind: "fallback", reason: "source-conflict" });
  });
});
