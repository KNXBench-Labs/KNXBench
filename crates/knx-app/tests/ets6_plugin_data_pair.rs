//! A plug-in edit changes only that plug-in's stored bytes, and every plug-in byte survives import.
//!
//! Input: [`knx_testsupport::ets6_plugin_pair_paths`] — two ETS6 project
//! archives of the same real project taken on the same day, the second after
//! one text was changed in a manufacturer plug-in editor (econ SmartSensor). ETS keeps
//! that editor's configuration in two places KNXBench must never interpret or
//! drop: the device's `BinaryData` blob and the `ExtraData/*.rbg` table the
//! plug-in's export handler writes (ADR-0025: preserved, never executed).
//!
//! The test checks, for both files: a clean import; every plug-in entry
//! stored with the archive's exact bytes; the stored entries unchanged by a
//! save/reopen cycle. Across the pair: the only stored entries whose bytes
//! differ are the project signature and the edited device's two plug-in
//! entries (plus KNXBench's own import report, which records source hashes).
//! Nothing manufacturer- or owner-written is printed.

use std::collections::{BTreeMap, BTreeSet};
use std::io::Read;
use std::path::Path;

/// The edited SmartSensor's plug-in entries and the project signature.
const EXPECTED_DIFFERENCES: &[&str] = &[
    "P-0512.signature",
    "P-0512/BinaryData/b113ce24-349e-45db-8ad5-c2a7003d0edf.dat",
    "P-0512/ExtraData/393256.rbg",
];

/// Generated by KNXBench itself on every import; it embeds source digests.
const OWN_REPORT: &str = "knxbench-native/import-report.json";

fn archive_entry(path: &Path, name: &str) -> Vec<u8> {
    let file = std::fs::File::open(path).expect("pair file readable");
    let mut archive = zip::ZipArchive::new(file).expect("pair file is a ZIP");
    let mut member = archive.by_name(name).expect("archive member present");
    let mut bytes = Vec::new();
    member
        .read_to_end(&mut bytes)
        .expect("archive member readable");
    bytes
}

fn plugin_entries(path: &Path) -> Vec<String> {
    let file = std::fs::File::open(path).expect("pair file readable");
    let archive = zip::ZipArchive::new(file).expect("pair file is a ZIP");
    archive
        .file_names()
        .filter(|n| !n.ends_with('/') && (n.contains("/BinaryData/") || n.contains("/ExtraData/")))
        .map(str::to_owned)
        .collect()
}

/// Imports `path` into a fresh store, checks the plug-in entries and a
/// save/reopen cycle, and returns whole-file opaque entries by source path.
fn import_and_check(path: &Path) -> BTreeMap<String, Vec<u8>> {
    let dir = tempfile::tempdir().unwrap();
    let native = dir.path().join("pair.knxdb");
    let conn = knx_store::open_and_migrate(&native).unwrap();
    let imported = knx_app::import_ets_project(path, &conn).unwrap();
    assert_eq!(imported.report.error_count(), 0, "{}", path.display());

    let opaque = knx_store::load_opaque(&conn).unwrap();
    let whole_files: BTreeMap<String, Vec<u8>> = opaque
        .iter()
        .filter(|e| e.xpath.is_empty())
        .map(|e| (e.source_path.clone(), e.bytes.clone()))
        .collect();

    let plugin = plugin_entries(path);
    assert!(
        plugin.iter().any(|n| n.contains("/BinaryData/"))
            && plugin.iter().any(|n| n.contains("/ExtraData/")),
        "pair file carries both plug-in channels"
    );
    for name in &plugin {
        let stored = whole_files
            .get(name)
            .unwrap_or_else(|| panic!("plug-in entry {name} not retained"));
        assert!(
            *stored == archive_entry(path, name),
            "plug-in entry {name} altered"
        );
    }

    knx_store::save_project(&conn, &imported.project).unwrap();
    drop(conn);
    let conn = knx_store::open_existing_and_migrate(&native).unwrap();
    assert_eq!(
        knx_store::load_opaque(&conn).unwrap(),
        opaque,
        "save/reopen changed opaque data"
    );
    whole_files
}

#[test]
#[ignore = "requires the gitignored OriginalData/ corpus; run with --ignored"]
fn plugin_edit_changes_only_the_plugin_entries_and_all_bytes_survive() {
    assert!(
        knx_testsupport::ets6_plugin_pair_available(),
        "ETS6 plug-in export pair missing (see knx_testsupport::ets6_plugin_pair_paths)"
    );
    let (unchanged, edited) = knx_testsupport::ets6_plugin_pair_paths();
    let a = import_and_check(&unchanged);
    let b = import_and_check(&edited);

    let a_names: BTreeSet<&String> = a.keys().collect();
    let b_names: BTreeSet<&String> = b.keys().collect();
    assert_eq!(a_names, b_names, "both imports retain the same entries");

    let differing: BTreeSet<&str> = a
        .iter()
        .filter(|(name, bytes)| b.get(*name) != Some(*bytes))
        .map(|(name, _)| name.as_str())
        .filter(|name| *name != OWN_REPORT)
        .collect();
    let expected: BTreeSet<&str> = EXPECTED_DIFFERENCES.iter().copied().collect();
    assert_eq!(differing, expected);
}
