// Run in an isolated Playwright CLI session already showing index.html:
// playwright-cli run-code --filename verify-browser.js
async (page) => {
  const checks = [], unexpectedRequests = [], errors = [];
  const originalUrl = page.url();
  if (!originalUrl.endsWith('/lcars/index.html')) throw new Error('Open the offline LCARS index.html first.');
  const assert = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  const requests = (request) => { if (!request.url().startsWith('file:') && !request.url().startsWith('data:')) unexpectedRequests.push(request.url()); };
  const consoleError = (message) => { if (message.type()==='error') errors.push(message.text()); };
  const pageError = (error) => errors.push(error.message);
  page.on('request',requests); page.on('console',consoleError); page.on('pageerror',pageError);
  const fresh = async () => { await page.setViewportSize({width:1600,height:1000}); await page.emulateMedia({reducedMotion:'no-preference'}); await page.goto(originalUrl); };
  const applyName = async (name) => { await page.locator('#entity-name').fill(name); await page.getByRole('button',{name:'Übernehmen',exact:true}).click(); };
  const dirty = async () => (await page.locator('#save-state').textContent()).includes('nicht demo-gesichert');
  try {
    await fresh();
    await page.evaluate(()=>document.fonts.ready);
    assert(await page.getByRole('table',{name:'Gruppenadressen',exact:true}).count()===1,'native table');
    assert(await page.locator('#address-rows tr').count()===22,'all 22 fixture rows admitted');
    assert(await page.evaluate(()=>document.fonts.check('13px Inter') && document.fonts.check('21px "Space Grotesk"') && document.fonts.check('12px "JetBrains Mono"')),'embedded fonts loaded');
    await page.getByRole('button',{name:'Küche · Pendelleuchte',exact:true}).focus();
    await page.keyboard.press('Enter');
    assert(await page.locator('#entity-title').textContent()==='Küche · Pendelleuchte','keyboard name activation opens matching inspector');
    await page.getByRole('checkbox',{name:'Wohnzimmer · Decke markieren',exact:true}).check();
    assert(await page.locator('#entity-title').textContent()==='Küche · Pendelleuchte','checkbox marking is independent of active entity');
    assert(await page.locator('#checked-count').textContent()==='1 markiert','mark count is factual');
    await page.locator('#filter').fill('Küche');
    assert(await page.locator('#address-rows tr').count()===4,'filter shows matching fixture rows');
    await page.getByRole('checkbox',{name:'Sichtbare Einträge markieren',exact:true}).check();
    assert(await page.locator('#checked-count').textContent()==='5 markiert','select-all only marks visible rows and retains earlier marks');
    await page.locator('#filter').fill('Kein Treffer');
    assert(await page.locator('#empty-results').isVisible(),'empty filter feedback');
    await page.locator('#filter').fill('');
    await page.getByRole('button',{name:'Wohnzimmer · Decke',exact:true}).click();
    await page.locator('#entity-name').fill('Wohnzimmer · Entwurf');
    await page.getByRole('button',{name:'Küche · Pendelleuchte',exact:true}).click();
    await page.getByRole('button',{name:'Wohnzimmer · Decke',exact:true}).click();
    assert(await page.locator('#entity-name').inputValue()==='Wohnzimmer · Entwurf','draft survives selection changes');
    await page.locator('#entity-ga').fill('32/0/1');
    await page.getByRole('button',{name:'Übernehmen',exact:true}).click();
    assert(await page.locator('#form-error').isVisible() && await page.locator('#entity-address').textContent()==='1/0/1','invalid address refuses mutation');
    await page.locator('#entity-ga').fill('1/0/2');
    await page.getByRole('button',{name:'Übernehmen',exact:true}).click();
    assert((await page.locator('#form-error').textContent()).includes('bereits vergeben'),'duplicate address refuses mutation');
    await page.locator('#entity-ga').fill('1/0/1');
    await page.getByRole('button',{name:'Übernehmen',exact:true}).click();
    assert(await dirty(),'valid edit is explicitly dirty');
    await page.getByRole('button',{name:'Demo sichern',exact:true}).click();
    assert(await page.locator('#feedback progress').count()===1,'pending demo exposes native progress');
    await page.waitForTimeout(1400);
    assert((await page.locator('#feedback').textContent()).includes('nur Arbeitsspeicher') && !(await dirty()),'success only acknowledges memory snapshot');
    await applyName('Wohnzimmer · Schreibfehlerprobe');
    await page.locator('#save-outcome').selectOption('error');
    await page.getByRole('button',{name:'Demo sichern',exact:true}).click();
    await page.waitForTimeout(1400);
    assert(await dirty() && await page.locator('#feedback').getAttribute('role')==='alert','simulated failure retains dirty data with alert');
    await page.setViewportSize({width:1280,height:900});
    await page.screenshot({path:'output/playwright/lcars-error.png'});
    await page.setViewportSize({width:1600,height:1000});
    await page.locator('#save-outcome').selectOption('success');
    await page.getByRole('button',{name:'Demo sichern',exact:true}).click();
    await page.getByRole('button',{name:'Abbrechen',exact:true}).click();
    await page.waitForTimeout(1400);
    assert(await dirty() && (await page.locator('#feedback').textContent()).includes('abgebrochen'),'cancel retains dirty data without late success');
    await page.getByRole('button',{name:'Demo sichern',exact:true}).click();
    await applyName('Wohnzimmer · Neuerer Stand');
    await page.waitForTimeout(1400);
    assert(await dirty() && (await page.locator('#feedback').textContent()).includes('Neuere Änderungen'),'older snapshot cannot acknowledge newer edit');
    await page.locator('#entity-name').focus();
    await page.keyboard.press('Control+s');
    await page.keyboard.press('Control+s');
    assert(await page.locator('#feedback progress').count()===1,'repeated save shortcut creates one pending operation');
    await page.getByRole('button',{name:'Abbrechen',exact:true}).click();
    const upperFloor = page.locator('.project-tree summary').filter({hasText:'Obergeschoss'});
    await upperFloor.focus();
    assert(await upperFloor.evaluate(summary=>summary===document.activeElement),'native disclosure receives keyboard focus');
    await page.keyboard.press('Enter');
    assert(await upperFloor.evaluate(summary=>summary.parentElement.open),'native disclosure works with keyboard');
    await page.locator('[data-room="Schlafzimmer"]').click();
    assert(await page.locator('#address-rows tr').count()===4,'project room scopes real fixture rows');
    await page.locator('[data-room=""]').click();
    await page.locator('.primary-nav').getByRole('button',{name:'Topologie',exact:true}).click();
    assert(await page.locator('#view-title').textContent()==='Topologie','workspace navigation changes real view');
    await page.waitForTimeout(30);
    assert(await page.evaluate(()=>document.getAnimations().length)>0,'enabled motion has actual live action feedback');
    await page.locator('#motion').selectOption('off');
    await page.waitForTimeout(40);
    assert(await page.evaluate(()=>document.getAnimations().length)===0,'off cancels running animations and transitions');
    await page.locator('#motion').selectOption('standard');
    await page.locator('.primary-nav').getByRole('button',{name:'Gruppenadressen',exact:true}).click();
    await page.waitForTimeout(30);
    assert(await page.evaluate(()=>document.getAnimations().length)>0,'reenabled action feedback is live');
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.waitForTimeout(40);
    assert(await page.evaluate(()=>document.getAnimations().length)===0 && await page.locator('html').getAttribute('data-effective-motion')==='off','OS reduced motion cancels running feedback');
    await page.emulateMedia({reducedMotion:'no-preference'});
    await page.waitForTimeout(550);
    assert(await page.evaluate(()=>document.getAnimations().length)===0,'no idle animation loop');
    const rowHeight = await page.locator('#address-rows tr').first().evaluate(row=>row.getBoundingClientRect().height);
    await page.locator('#density').selectOption('comfortable');
    const roomyHeight = await page.locator('#address-rows tr').first().evaluate(row=>row.getBoundingClientRect().height);
    assert(roomyHeight>rowHeight,'comfortable density increases actual row geometry');
    await page.locator('#presentation').selectOption('neutral');
    assert(await dirty() && await page.locator('#entity-title').textContent()==='Wohnzimmer · Neuerer Stand' && await page.locator('#density').inputValue()==='comfortable','presentation switch preserves data and independent density');
    await page.locator('#presentation').selectOption('lcars');
    await page.locator('#inspector-close').click();
    assert(!(await page.locator('#inspector').isVisible()) && await page.locator('#inspector-toggle').evaluate(button=>button===document.activeElement),'inspector close restores focus to trigger');
    await page.locator('#inspector-toggle').click();
    await page.keyboard.press('Control+k');
    assert(await page.locator('#filter').evaluate(input=>input===document.activeElement),'search shortcut preserves visible keyboard focus');
    const focusStyle = await page.locator('#filter').evaluate(input=>getComputedStyle(input).outlineStyle);
    assert(focusStyle!=='none','keyboard focus has rendered outline');
    await page.locator('#reset-open').click();
    assert(await page.locator('#reset-cancel').evaluate(button=>button===document.activeElement),'reset confirmation initially focuses cancel');
    await page.keyboard.press('Escape');
    assert(await dirty() && !(await page.locator('#reset-dialog').isVisible()),'Escape cancels reset without data loss');
    await page.locator('#reset-open').click(); await page.locator('#reset-confirm').click();
    assert(await page.locator('#entity-title').textContent()==='Wohnzimmer · Decke' && !(await dirty()),'explicit reset restores fixture state');
    await page.locator('#density').selectOption('compact'); await page.locator('#motion').selectOption('off');
    await page.locator('#about-open').click();
    assert(await page.locator('#about-dialog').isVisible() && (await page.locator('#font-notices').textContent()).includes('SIL OPEN FONT LICENSE'),'offline explanation includes embedded font notices');
    await page.keyboard.press('Escape');
    await page.screenshot({path:'output/playwright/lcars-desktop.png'});
    const tableOverflow = await page.locator('#table-scroll').evaluate(el=>el.scrollHeight>el.clientHeight);
    assert(tableOverflow,'large fixture list has real vertical table overflow');
    for (const [width,height,name] of [[768,1000,'narrow'],[720,620,'zoom-layout'],[480,900,'small']]) {
      await page.setViewportSize({width,height});
      const overflow = await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
      assert(!overflow,`${name}: no global horizontal overflow`);
      assert(await page.locator('#save-outcome').isVisible() && await page.locator('#demo-save').isVisible(),`${name}: simulation controls stay reachable`);
      const scroll = await page.locator('#table-scroll').evaluate(el=>el.scrollWidth>el.clientWidth);
      assert(scroll,`${name}: table overflow stays local`);
      if (name==='small') assert(await page.locator('#table-scroll').evaluate(el=>el.clientHeight)>=100,'small: meaningful table rows remain visible');
      await page.screenshot({path:`output/playwright/lcars-${name}.png`});
    }
    await page.setViewportSize({width:1600,height:1000});
    assert(unexpectedRequests.length===0,'no external page requests');
    assert(errors.length===0,'no final-source browser console or script errors');
    const result={passed:checks.length,failed:0,checks,viewports:[[1600,1000],[1280,900],[768,1000],[720,620],[480,900]],zoomBoundary:'720px layout viewport represents 200% zoom on a 1440px-wide window; browser chrome zoom was not driven',networkRequests:unexpectedRequests,consoleErrors:errors};
    await page.evaluate(result=>window.__lcarsVerification=result,result);
    console.log('LCARS_VERIFICATION '+JSON.stringify(result));
  } finally {
    page.removeListener('request',requests); page.removeListener('console',consoleError); page.removeListener('pageerror',pageError);
  }
}
