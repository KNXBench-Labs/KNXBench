/** Playwright CLI recipe: exercise the standalone page, return named assertions and capture real frames. */
async (page) => {
  const checks = [], screenshots = [], errors = [], externalRequests = [];
  const origin = new URL(page.url()).origin;
  const verify = (name, condition) => { if (!condition) throw new Error(`FAIL: ${name}`); checks.push(name); };
  const text = selector => page.locator(selector).innerText();
  const capture = async name => { const path = `output/playwright/final/${name}.png`; await page.screenshot({ path, fullPage: false }); screenshots.push(path); };
  page.on('pageerror', error => errors.push(String(error)));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('request', request => { const url = request.url(); if (!url.startsWith(origin) && !url.startsWith('data:') && !url.startsWith('file:')) externalRequests.push(url); });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => localStorage.removeItem('knxbench.ga-study.view.v1'));
  await page.reload();
  verify('default tree and exactly four view choices', await page.locator('[data-view]').count() === 4 && await page.locator('[data-view="tree"]').getAttribute('aria-pressed') === 'true');
  verify('fictional data are frozen and counted accurately', await page.evaluate(() => GaStudy.addresses.length === 36 && Object.isFrozen(GaStudy.addresses)));
  const sourceBefore = await page.evaluate(() => JSON.stringify(GaStudy.addresses));
  await page.locator('[data-action="expand-all"]').click();
  verify('tree exposes all 36 identities after expansion', await page.locator('[data-address]').count() === 36);
  await page.locator('[data-action="collapse-all"]').click();
  verify('tree collapses all address leaves', await page.locator('[data-address]').count() === 0);
  await page.locator('[data-key="m:1"]').focus();
  await page.keyboard.press('Enter');
  verify('native Enter expands focused main group and preserves focus', await page.locator('[data-key="m:1"]').getAttribute('aria-expanded') === 'true' && await page.locator('[data-key="m:1"]').evaluate(el => el === document.activeElement));
  await page.locator('[data-key="s:1:0"]').click();
  await page.locator('[data-action="select"][data-id="light-kitchen-switch"]').click();
  verify('address click fills shared inspector', await page.locator('[data-inspected="light-kitchen-switch"]').count() === 1);
  for (const view of ['tree', 'columns', 'atlas', 'matrix']) {
    await page.locator(`[data-view="${view}"]`).click();
    verify(`${view} retains selected identity and count`, await page.locator('[data-inspected="light-kitchen-switch"]').count() === 1 && (await text('#selection-status')).includes('1 ausgewählt'));
    verify(`${view} uses bounded desktop workspace`, await page.locator('.canvas').evaluate(el => el.clientHeight >= 180 && el.getBoundingClientRect().bottom < innerHeight));
    await capture(`desktop-${view}`);
  }
  await page.locator('[data-view="columns"]').click();
  await page.locator('#workspace [data-action="scope-main"][data-id="1"]').click();
  await page.locator('#workspace [data-action="scope-middle"][data-id="0"]').click();
  verify('column navigation scopes to six switch addresses', (await text('#result-count')) === '6 von 36 Adressen');
  await page.locator('[data-action="check"][data-id="light-living-switch"]').check();
  verify('checkbox adds a second identity', (await text('#selection-status')).includes('2 ausgewählt'));
  await page.locator('[data-view="atlas"]').click();
  verify('atlas opens the same address scope and retains both selections', await page.locator('.atlas-grid.addresses [data-address]').count() === 6 && await page.locator('.atlas-tile.selected').count() === 2);
  await capture('desktop-atlas-addresses');
  await page.locator('#breadcrumbs [data-action="scope-main"][data-id="all"]').click();
  verify('atlas breadcrumb returns to five main-group tiles', await page.locator('.atlas-grid [data-action="scope-main"]').count() === 5);
  await page.locator('.atlas-grid [data-action="scope-main"][data-id="2"]').click();
  verify('atlas drills into two middle groups', await page.locator('.atlas-grid [data-action="scope-middle"]').count() === 2);
  await page.locator('.atlas-grid [data-action="scope-middle"][data-id="1"]').click();
  verify('atlas reaches all four blind position addresses', await page.locator('.atlas-grid.addresses [data-address]').count() === 4);
  await page.locator('#reset').click();
  await page.locator('[data-view="tree"]').click();
  await page.locator('#search').fill('9.001');
  verify('DPT search finds six temperature addresses in actual UI', (await text('#result-count')) === '6 von 36 Adressen');
  await page.locator('#search').fill('1.0.1');
  verify('dotted group address search finds exact kitchen switch identity', await page.locator('[data-address="light-kitchen-switch"]').count() === 1);
  await page.locator('#search').fill('does-not-exist');
  verify('empty search is explicit and keeps inspector', (await text('#workspace')).includes('Keine passenden Adressen') && await page.locator('[data-inspected="light-living-switch"]').count() === 1);
  verify('hidden selected identities are reported', (await text('#selection-status')).includes('2 außerhalb'));
  await page.locator('#reset').click();
  await page.locator('#filter').selectOption('conflict');
  for (const view of ['tree', 'columns', 'atlas', 'matrix']) {
    await page.locator(`[data-view="${view}"]`).click();
    verify(`${view} preserves conflict filter across switches`, (await text('#result-count')) === '1 von 36 Adressen' && await page.locator('#filter').inputValue() === 'conflict');
  }
  await page.locator('#reset').click();
  await page.locator('#filter').selectOption('unlinked');
  verify('confirmed absent links exclude unknown links in UI', (await text('#result-count')) === '1 von 36 Adressen' && await page.locator('[data-address="spare-unlinked"]').count() === 1);
  await page.locator('#reset').click();
  await page.locator('#search').fill('Reserve');
  await page.locator('[data-view="matrix"]').click();
  verify('matrix distinguishes unknown from absent cells', await page.locator('[data-address="spare-unknown"] .matrix-cell.unknown').count() === 6 && await page.locator('[data-address="spare-unlinked"] .matrix-cell.none').count() === 6);
  await page.locator('#reset').click();
  await page.locator('[data-id="light-kitchen-switch"][data-object="light-button"]').click();
  verify('matrix cell explains its exact object and direction', (await text('.object-detail')).includes('Bedienung Licht') && (await text('.object-detail')).includes('Send-Verknüpfung'));
  await page.locator('#matrix-family').selectOption('all');
  verify('matrix object filter changes columns only', await page.locator('.matrix-table thead th').count() === 13 && (await text('#result-count')) === '36 von 36 Adressen');
  await page.locator('#theme').click();
  verify('dark theme does not change selection', await page.locator('html').getAttribute('data-theme') === 'dark' && await page.locator('[data-inspected="light-kitchen-switch"]').count() === 1);
  await capture('desktop-matrix-dark');
  await page.locator('#theme').click();
  await page.locator('#notation').selectOption('two');
  verify('notation changes selected display not identity or stored range', (await text('.inspector-address')) === '1/1' && (await text('#inspector')).includes('Beleuchtung / Schalten') && await page.locator('[data-inspected="light-kitchen-switch"]').count() === 1);
  await page.locator('[data-view="columns"]').click();
  verify('two-level columns omit middle column', await page.locator('.browser-column').count() === 2);
  await page.locator('[data-view="tree"]').click();
  await page.locator('[data-action="expand-all"]').click();
  verify('two-level tree has no artificial middle level and includes unassigned addresses', await page.locator('.level-two').count() === 0 && await page.locator('[data-address]').count() === 36 && await page.locator('[data-address="spare-unknown"]').count() === 1);
  await capture('desktop-tree-two-level');
  await page.locator('[data-view="atlas"]').click();
  await page.locator('.atlas-grid [data-action="scope-main"][data-id="1"]').click();
  verify('two-level atlas opens directly to 19 address tiles', await page.locator('.atlas-grid.addresses [data-address]').count() === 19);
  await capture('desktop-atlas-two-level');
  await page.locator('#reset').click();
  await page.locator('#notation').selectOption('three');
  await page.locator('[data-view="tree"]').click();
  await page.locator('#tasks-toggle').click();
  verify('comparison tasks are interactive', await page.locator('#tasks').isVisible() && await page.locator('#tasks-toggle').getAttribute('aria-expanded') === 'true');
  await page.locator('#tasks-toggle').click();
  await page.setViewportSize({ width: 400, height: 900 });
  for (const view of ['tree', 'columns', 'atlas', 'matrix']) {
    await page.locator(`[data-view="${view}"]`).click();
    verify(`${view} compact layout has no global horizontal overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    verify(`${view} compact workspace retains at least 280px for data`, await page.locator('.canvas').evaluate(el => el.clientHeight >= 280));
    await capture(`compact-${view}`);
  }
  await page.locator('.inspector-header').scrollIntoViewIfNeeded();
  verify('compact inspector remains reachable by normal page scrolling', await page.locator('.inspector-header').evaluate(el => el.getBoundingClientRect().top >= 0 && el.getBoundingClientRect().bottom <= innerHeight));
  verify('compact inspector retains the selected identity', await page.locator('[data-inspected="light-kitchen-switch"]').count() === 1);
  await capture('compact-inspector');
  await page.locator('h1').scrollIntoViewIfNeeded();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('[data-view="atlas"]').click();
  await page.reload();
  verify('preferred view is remembered after reload', await page.locator('[data-view="atlas"]').getAttribute('aria-pressed') === 'true');
  verify('all navigation leaves canonical fictional source byte-equivalent', await page.evaluate(() => JSON.stringify(GaStudy.addresses)) === sourceBefore);
  verify('no JavaScript or console errors', errors.length === 0);
  verify('no external requests', externalRequests.length === 0);
  return { passed: checks.length, checks, screenshots, errors, externalRequests };
}
